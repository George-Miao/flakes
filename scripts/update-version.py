#!/usr/bin/env python3

import html
import json
import re
import subprocess
from datetime import datetime, timezone
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
REPORT = ROOT / "VERSION.md"


def git(*args):
    return subprocess.check_output(["git", *args], cwd=ROOT, text=True)


def package_platform(name):
    match = re.fullmatch(r"(.+)-(linux|darwin)(?:-(x64|arm64))?(?:-(stable|insider))?", name)
    if match is None:
        return name, ""
    package, system, architecture, channel = match.groups()
    if package == "orca-bin":
        package = "orca"
    if channel == "insider":
        package += "-insider"
    platform = system if architecture is None else f"{system}-{architecture}"
    return package, platform


def read_report():
    records = {}
    package = ""
    if REPORT.exists():
        for line in REPORT.read_text().splitlines():
            if not line.startswith("| "):
                continue
            cells = [html.unescape(cell.strip()) for cell in line.split("|")[1:-1]]
            if len(cells) == 4 and cells[0] not in {"Package name", "---"}:
                name, platform, version, updated = cells
                package = name or package
                records[package, platform] = (version, updated)
    return records


def update_times(path, entries, labels, previous, now):
    times = {}
    pending = set()
    for name, entry in entries.items():
        old = previous.get(labels[name])
        if old is not None and old[0] == entry["version"]:
            times[name] = old[1]
        else:
            times[name] = now
            pending.add(name)

    if not pending:
        return times

    relative = path.relative_to(ROOT).as_posix()
    history = git("log", "--format=%H %cI", "--name-status", "--no-renames", "--", relative)
    revisions = [line for line in history.splitlines() if line]
    for index in range(0, len(revisions), 2):
        if not pending:
            break
        commit, timestamp = revisions[index].split()
        if revisions[index + 1].startswith("D\t"):
            versions = {}
        else:
            versions = json.loads(git("show", f"{commit}:{relative}"))
        updated = datetime.fromisoformat(timestamp).astimezone(timezone.utc)
        for name in pending.copy():
            if versions.get(name, {}).get("version") == entries[name]["version"]:
                times[name] = updated.strftime("%Y-%m-%d %H:%M:%S UTC")
            else:
                pending.remove(name)
    return times


def cell(value):
    return html.escape(value).replace("|", "&#124;").replace("\n", "&#10;").replace("\r", "&#13;")


def main():
    paths = sorted((ROOT / "generated").glob("*/generated.json"))
    if not paths:
        raise SystemExit("No generated source records found.")

    sources = [(path, json.loads(path.read_text())) for path in paths]
    labels = {name: package_platform(name) for _, entries in sources for name in entries}
    platforms = {}
    for package, platform in labels.values():
        platforms.setdefault(package, set()).add(platform)
    labels = {
        name: (package, platform if len(platforms[package]) > 1 else "")
        for name, (package, platform) in labels.items()
    }

    previous = read_report()
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC")
    lines = [
        "This file is automatically generated. Do not edit it manually.",
        "",
        "# Fetched versions",
        "",
        "Last updated is the time when the fetched version last changed.",
        "The first report uses Git history. Later runs keep the time unless the version changes.",
        "Packages are sorted by their latest update, newest first.",
        "",
        "| Package name | Platform | Version | Last updated |",
        "| --- | --- | --- | --- |",
    ]
    rows_by_package = {}
    for path, entries in sources:
        times = update_times(path, entries, labels, previous, now)
        for name, entry in entries.items():
            package, platform = labels[name]
            rows_by_package.setdefault(package, []).append(
                (package, platform, entry["version"], times[name])
            )
    groups = sorted(
        rows_by_package.values(),
        key=lambda group: max(row[3] for row in group),
        reverse=True,
    )
    for group in groups:
        for index, values in enumerate(sorted(group, key=lambda row: row[3], reverse=True)):
            if index:
                values = ("", *values[1:])
            lines.append("| " + " | ".join(cell(value) for value in values) + " |")

    REPORT.write_text("\n".join(lines) + "\n")
    print("Updated VERSION.md.")


if __name__ == "__main__":
    main()
